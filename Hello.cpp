// This library is used for input and output operations
#include <iostream>

// This allows us to use standard names like cout without writing std::
using namespace std;

// The main() function is the starting point of every C++ program
int main()
{

    // cout is used to print output on the screen
    // "Hello World" will be displayed
    // \n moves the cursor to the next line
    cout << "Hello World\n";

    // This line prints the second message on the next line
    cout << "Welcome to world of programming";

    // return 0 means the program ended successfully
    return 0;
}