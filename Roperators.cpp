#include <iostream>
using namespace std;

int main() {

    int a = 10;
    int b = 5;

    cout << "value of a = " << a << endl;
    cout << "Value of b = " << b << endl;

    cout << "a == b : " << (a == b) << endl;
    cout << "a != b : " << (a != b) << endl;
    cout << "a > b : " << (a > b) << endl;
    cout << "a < b : " << (a < b) << endl;
    cout << "a >= b : " << (a >= b) << endl;
    cout << "a <= b : " << (a <= b) << endl;

    return 0;
}